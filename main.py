LIMIT = 500
MAX_WORKERS = 1


def fetch_page(offset, url):
    session = create_session()
    params = {
        "limit": LIMIT,
        "offset": offset
    }

    response = session.get(url, params=params, timeout=120)
    response.raise_for_status()
    return response.json()

def get_total_results(url):
    session = create_session()
    params = {
        "limit": 1,
        "offset": 0,
        "totalResults": "true"
    }

    response = session.get(url, params=params, timeout=120)
    response.raise_for_status()
    data = response.json()

    return data.get("totalResults", 0)

def get_all_records(url):
    total_results = get_total_results(url)
    offsets = list(range(0, total_results, LIMIT))
    all_records = []

    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as executor:
        future_to_offset = {
            executor.submit(fetch_page, offset, url): offset
            for offset in offsets
        }

        for future in as_completed(future_to_offset):
            offset = future_to_offset[future]
            try:
                data = future.result()
                items = data.get("items", [])
                all_records.extend(items)
                print(f"Fetched offset {offset} from {url.split('/')[-1]}, records: {len(items)}")
            except Exception as e:
                print(f"Error fetching offset {offset}: {e}")

    return all_records

