execution_times = {}



def measure_time(func):
    @wraps(func)
    def wrapper(*args, **kwargs):
        start = time.perf_counter()

        result = func(*args, **kwargs)

        end = time.perf_counter()

        execution_times[func.__name__] = round(end - start,6)  # seconds
        return result

    return wrapper

